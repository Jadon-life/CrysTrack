import { NextResponse } from 'next/server';
import { createClient } from '@/lib/supabase/server';
import { readWealthReport, wealthReadHeaders } from '@/lib/wealth-report-server';
import { readAiPrivacy, beginAi, finishAi, assertAiOrigin, aiFailure } from '@/lib/ai/privacy-server';
import { scopedWealthContext } from '@/lib/ai/scoped-context';
import { analyzeWealthMetricsWithOpenRouter } from '@/lib/ai/wealth-openrouter';

export const runtime = 'nodejs';

export async function POST(request: Request) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });

  try { assertAiOrigin(request); } catch(e) { return aiFailure(e); }
  let summary;
  try {
    summary = (await readWealthReport(supabase, user.id)).summary;
  } catch {
    return NextResponse.json(
      { error: 'Wealth is temporarily unavailable. No balances are assumed.' },
      { status: 503, headers: wealthReadHeaders },
    );
  }


  try {
    const permission = await readAiPrivacy(supabase);
    if (!permission.enabled || !permission.wealthEnabled || !process.env.OPENROUTER_API_KEY) {
      return NextResponse.json({source:'deterministic',insight:{headline:'Local spending pattern',summary:summary.deterministicRemark,observation:'Calculated locally by CrysTrack, not generated by an AI provider. AI or Wealth sharing is off, unavailable or not configured.',next_action:'Review your recorded money in Wealth.',confidence:summary.dataMonths>=2?'medium':'low'}},{headers:wealthReadHeaders});
    }
    const lease = await beginAi(supabase,'wealth_legacy',request.signal);
    const insight = await analyzeWealthMetricsWithOpenRouter(await scopedWealthContext(supabase,user.id),lease);
    if (!insight) {
      return NextResponse.json({
        source: 'deterministic',
        insight: {
          headline: 'Spending pattern',
          summary: summary.deterministicRemark,
          observation:
            'CrysTrack is using deterministic metrics because AI analysis is not configured.',
          next_action: 'Keep recording actual income, expenses and savings consistently.',
          confidence: summary.dataMonths >= 2 ? 'medium' : 'low',
        },
      });
    }

    return NextResponse.json(await finishAi(lease, {insight}), {headers:wealthReadHeaders});
  } catch (error: any) {
    return NextResponse.json({
      source: 'deterministic',
      insight: {
        headline: 'Spending pattern',
        summary: summary.deterministicRemark,
        observation:
          'AI commentary was unavailable, so CrysTrack kept the local deterministic analysis.',
        next_action: 'Review the category with the largest change against your recent baseline.',
        confidence: summary.dataMonths >= 2 ? 'medium' : 'low',
      },
    });
  }
}
